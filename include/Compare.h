// Правило сравнения «меньше» по умолчанию для упорядоченных структур
// (отсортированная последовательность, АВЛ-дерево).
//
// Структуры принимают правило сравнения параметром шаблона, а не
// полагаются только на operator<. Это позволяет, например, хранить пары
// «ключ, значение» и сравнивать их только по ключу (PairKeyLess в Pair.h),
// не меняя смысла operator== у самих пар.
//
// Требование к T: определён operator<, задающий строгий слабый порядок.
// Два элемента считаются равными, если ни один не меньше другого.

template <class T>
class Less
{
public:
    bool operator()(const T& left, const T& right) const;
};

template <class T>
bool Less<T>::operator()(const T& left, const T& right) const
{
    return left < right;
}
